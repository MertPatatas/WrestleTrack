export function translate(lang: 'es' | 'en', key: MessageKey, vars?: Record<string, string | number>): string {
  const text = messages[lang][key] ?? messages.es[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : text;
}
